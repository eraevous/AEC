"""Reconstruct proposed history from reviewed input; never infer acceptance.

Usage: PYTHONPATH=src python3 tools/reconstruct_decisions.py [ROOT]
Input: .aec/reconstructed/2026-10-history.jsonl
Output: appended .aec/records.jsonl and generated docs/decisions-to-confirm.md.
All inputs and source quotations are validated before any output is written.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import re
from pathlib import Path

from aec.records import Record, Store, check


REQUIRED = {'id', 'text', 'source_path', 'source_section', 'source_quote'}
ALLOWED = REQUIRED | {'status', 'supersedes'}


def _rows(text: str) -> list[dict]:
    return [json.loads(line) for line in text.splitlines()
            if line.strip() and not line.lstrip().startswith('//')]


def _section(text: str, title: str) -> str:
    lines = text.splitlines(keepends=True)
    for i, line in enumerate(lines):
        m = re.match(r'^(#{1,6})\s+(.+?)\s*#*\s*$', line)
        if not m or m[2] != title:
            continue
        end = len(lines)
        for j in range(i + 1, len(lines)):
            next_heading = re.match(r'^(#{1,6})\s+', lines[j])
            if next_heading and len(next_heading[1]) <= len(m[1]):
                end = j
                break
        return ''.join(lines[i:end])
    raise ValueError('source section not found: ' + title)


def _store(rows: list[dict]) -> Store:
    common = {'id', 'version', 'type', 'text', 'subject', 'relations'}
    return Store([Record(id=r['id'], version=r['version'], type=r['type'], text=r.get('text', ''),
                         subject=r.get('subject'), relations=r.get('relations', []),
                         data={k: v for k, v in r.items() if k not in common}) for r in rows])


def confirmation(rows: list[dict]) -> str:
    latest = {}
    by_ref = {f"{r['id']}@{r['version']}": r for r in rows}
    for r in rows:
        if r.get('type') == 'decision' and r.get('origin') == 'reconstructed':
            if r['id'] not in latest or r['version'] > latest[r['id']]['version']:
                latest[r['id']] = r
    def cell(value):
        return str(value).replace('|', '\\|').replace('\n', ' ')
    out = ['# Reconstructed decisions for Zach to confirm', '',
           'Generated by tools/reconstruct_decisions.py. These are candidate reconstructions,',
           'all proposed; a source records what an artifact said, not verified owner consent.',
           'An empty confirmation column is intentional. No row authorizes a commitment.', '',
           '| Record | Proposed reconstruction | Source / section | SHA256 | Supersedes | Zach confirmation |',
           '| --- | --- | --- | --- | --- | --- |']
    for rid, d in sorted(latest.items()):
        source_ref = next(e['to'] for e in d['relations'] if e['rel'] == 'depends_on')
        s = by_ref[source_ref]
        prior = ', '.join(e['to'] for e in d['relations'] if e['rel'] == 'supersedes')
        out.append(f"| {rid}@{d['version']} | {cell(d['text'])} | {cell(s['ref'])} / {cell(s['section'])} | {s['sha256']} | {prior} |  |")
    return '\n'.join(out) + '\n'


def reconstruct(root: Path) -> dict:
    root = Path(root).resolve()
    input_path = root / '.aec/reconstructed/2026-10-history.jsonl'
    records_path = root / '.aec/records.jsonl'
    before = records_path.read_bytes() if records_path.exists() else b''
    existing = _rows(before.decode('utf-8'))
    store = _store(existing)
    entries = _rows(input_path.read_text(encoding='utf-8'))
    pending, seen = [], set()
    for entry in entries:
        if set(entry) - ALLOWED or not REQUIRED <= set(entry):
            raise ValueError('input requires id/text/source_path/source_section/source_quote; authority fields are forbidden')
        if entry.get('status', 'proposed') != 'proposed':
            raise ValueError('reconstructed decisions must be proposed')
        if any(not isinstance(entry[k], str) or not entry[k].strip() for k in REQUIRED):
            raise ValueError('required input fields must be nonempty strings')
        rid = entry['id']
        if not re.fullmatch(r'[A-Za-z0-9_.-]+', rid) or rid in seen:
            raise ValueError('invalid or duplicate decision id: ' + rid)
        seen.add(rid)
        path = (root / entry['source_path']).resolve()
        if not path.is_relative_to(root) or not path.is_file():
            raise ValueError('source must be a repository file: ' + entry['source_path'])
        raw = path.read_bytes()
        if entry['source_quote'] not in _section(raw.decode('utf-8'), entry['source_section']):
            raise ValueError('quote not found in source section: ' + rid)
        sha = hashlib.sha256(raw).hexdigest()
        prev = store.latest.get(rid)
        sid = 'HISTSRC-' + rid
        prev_source = store.latest.get(sid)
        if prev and (prev.type != 'decision' or prev.get('origin') != 'reconstructed'):
            raise ValueError('decision id collides with an existing record: ' + rid)
        if prev_source and (prev_source.type != 'source' or prev_source.get('origin') != 'reconstructed'):
            raise ValueError('source id collides with an existing record: ' + sid)
        normalized = {k: v for k, v in entry.items() if k != 'status'}
        if prev and prev.get('reconstruction') == normalized and prev.get('source_sha256') == sha:
            continue
        version = max(prev.version if prev else 0, prev_source.version if prev_source else 0) + 1
        source = dict(id=sid, version=version, type='source', origin='reconstructed', status='proposed',
                      text='Repository artifact for ' + rid, ref=entry['source_path'], sha256=sha,
                      section=entry['source_section'], quote=entry['source_quote'])
        if prev_source:
            source['relations'] = [{'rel': 'supersedes', 'to': prev_source.ref}]
        relations = [{'rel': 'depends_on', 'to': f'{sid}@{version}'}]
        for prior in dict.fromkeys([p for p in [prev.ref if prev else None, entry.get('supersedes')] if p]):
            relations.append({'rel': 'supersedes', 'to': prior})
        decision = dict(id=rid, version=version, type='decision', origin='reconstructed', status='proposed',
                        tier='candidate', subject='aec-scope', text=entry['text'],
                        source_sha256=sha, reconstruction=normalized, relations=relations)
        pending.extend([source, decision])
    all_rows = existing + pending
    failures = [f for f in check(_store(all_rows)) if f.level == 'error']
    if failures:
        raise ValueError('invalid reconstructed records: ' + '; '.join(f.msg for f in failures))
    by_ref = {f"{row['id']}@{row['version']}": row for row in all_rows}
    for row in all_rows:
        if row.get('origin') == 'reconstructed' and row['type'] == 'decision':
            for edge in row.get('relations', []):
                if edge['rel'] == 'supersedes' and by_ref[edge['to']]['type'] != 'decision':
                    raise ValueError('decision reversal must name another decision')
    table = confirmation(all_rows)
    # Guard against intervening edits; preserve existing bytes, including a missing final newline.
    if (records_path.read_bytes() if records_path.exists() else b'') != before:
        raise ValueError('records changed while reconstructing; rerun against the new state')
    if pending:
        records_path.parent.mkdir(parents=True, exist_ok=True)
        with records_path.open('ab') as stream:
            if before and not before.endswith(b'\n'):
                stream.write(b'\n')
            stream.write(''.join(json.dumps(row, ensure_ascii=False) + '\n' for row in pending).encode('utf-8'))
    output = root / 'docs/decisions-to-confirm.md'
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(table, encoding='utf-8')
    return {'appended': len(pending), 'decisions': len(entries), 'confirmation': str(output)}


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('root', nargs='?', default='.')
    args = parser.parse_args(argv)
    try:
        result = reconstruct(Path(args.root))
    except (ValueError, OSError) as error:
        parser.error(str(error))
    print(f"{result['appended']} reconstructed record(s) appended (proposed only, structural validation).")
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
